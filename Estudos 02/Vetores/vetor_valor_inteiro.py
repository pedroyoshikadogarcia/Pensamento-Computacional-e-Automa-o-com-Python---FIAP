# Criando uma lista de inteiros e atribuindo valores

vetor_inteiros = []
vetor_inteiros.append(10) #adiciona 10 na posicao 0
vetor_inteiros.append(1999) # Adiciona 1999 na posicao 1

print ("Valor inteiro na posicao 0: ", vetor_inteiros[0]) # Mostra a posicao 0 do vetor

ano_nascimento = vetor_inteiros[1] # Atribui a posicao 1 do vetor para a variavel ano_nascimento
print("Ano de Nascimento: ", ano_nascimento) 